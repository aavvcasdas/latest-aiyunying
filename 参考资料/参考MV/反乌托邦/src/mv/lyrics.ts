export const LINES = (() => {
  const items = RAW.map((r) => (Array.isArray(r[0]) ? r : [r]));
  return items.map((parts, i) => {
    const s = parts[0][0], next = items[i + 1], e = next ? next[0][0] : DUR - 0.3;
    const chars = [], ct = [];
    parts.forEach(([ps, txt], j) => {
      if (j) { chars.push(' ', ' '); ct.push(null, null); }
      const pe = j + 1 < parts.length ? parts[j + 1][0] : e, cs = Array.from(txt), span = Math.min(pe - ps, 4.2) * 0.86;
      cs.forEach((c, k) => { chars.push(c); ct.push(ps + (span * k) / cs.length); });
    });
    return { i, s, e, text: chars.join(''), parts: parts.map((p) => p[1]), chars, ct };
  });
})();

/** 句 i 里词 w 的各字唱到的时刻 */
export function wTimes(i, w) {
  const L = LINES[i], idx = L.text.indexOf(w);
  if (idx < 0) throw new Error(`[歌词] 第 ${i} 句「${L.text}」里没有「${w}」`);
  return Array.from(w).map((_, k) => L.ct[idx + k] ?? L.s);
}
export const wAt = (i, w) => wTimes(i, w)[0];
/** 句 i 里某个字每次出现的时刻（比如「看了又看」的两个看） */
export function charTimes(i, ch) { const L = LINES[i], out = []; L.chars.forEach((c, k) => { if (c === ch && L.ct[k] != null) out.push(L.ct[k]); }); return out; }
