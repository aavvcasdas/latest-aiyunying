/** 第 i 个字（a 与 b 连起来数，空格不算）的起音时间：半句内均分 */
export function charTimes(l: Line): number[] {
  const A = l.a.replace(/ /g, ""), B = l.b.replace(/ /g, "");
  const ta = A.split("").map((_, i) => l.t + ((l.m - l.t) * i) / A.length);
  const tb = B.split("").map((_, i) => l.m + ((l.e - l.m) * 0.8 * i) / B.length);
  return [...ta, ...tb];
}
