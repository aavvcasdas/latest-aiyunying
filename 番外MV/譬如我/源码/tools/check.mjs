import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

const req = createRequire(resolve(process.env.TOOLS_DIR || '.', 'package.json'))
const { chromium } = req('playwright')
const chromiumBin = (await import(pathToFileURL(req.resolve('@sparticuz/chromium')).href)).default
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || await chromiumBin.executablePath(), args: chromiumBin.args, headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 })
const out = process.env.QA_DIR || '.work/qa'
await mkdir(out, { recursive: true })
const errors = [], checks = []
page.on('pageerror', error => errors.push(error.message))
const pass = name => { checks.push(name); console.log('PASS', name) }
const audio = () => page.locator('audio').evaluate(a => ({ time: a.currentTime, paused: a.paused, duration: a.duration, muted: a.muted, speed: a.playbackRate, volume: a.volume }))
const button = name => page.getByRole('button', { name, exact: true })
try {
  await page.goto(process.env.BASE_URL || 'http://localhost:5173/', { waitUntil: 'networkidle' })
  await page.evaluate(() => {
    const a = document.querySelector('audio')
    const original = Object.getOwnPropertyDescriptor(HTMLMediaElement.prototype, 'currentTime')
    Object.defineProperty(a, 'currentTime', { get() { return original.get.call(a) }, set(t) { window.lastUserSeek = t; original.set.call(a, t) } })
  })
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(1000)
  assert.equal(await page.title(), '譬如我 · 鲸映放映厅')
  assert.equal(await page.locator('.chapter-card').count(), 4)
  assert.ok((await audio()).duration > 152)
  assert.equal(await page.locator('img').evaluateAll(images => images.every(i => i.complete && i.naturalWidth > 0)), true)
  await page.screenshot({ path: `${out}/desktop.png`, fullPage: true })
  pass('Initial artwork, four chapters, locally loaded fonts and audio metadata')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `${out}/mobile.png`, fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
  await page.setViewportSize({ width: 320, height: 720 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 320)
  pass('390px and 320px layouts without horizontal overflow')
  await page.setViewportSize({ width: 1440, height: 960 })
  await button('播放 MV').click()
  await page.waitForFunction(() => document.querySelector('audio').currentTime > .4)
  assert.equal((await audio()).paused, false)
  await button('暂停').click()
  const pausedTime = (await audio()).time
  await page.waitForTimeout(200)
  assert.equal((await audio()).time, pausedTime)
  pass('Real audio playback and pause')
  await page.locator('.chapter-card').nth(1).click()
  await page.waitForTimeout(450)
  assert.equal(await page.evaluate(() => window.lastUserSeek), 34.272)
  assert.ok((await audio()).time >= 34.272)
  await button('暂停').click()
  await page.screenshot({ path: `${out}/playing.png` })
  pass('Chapter seek to the measured verse onset')
  await button('播放设置').click()
  await button('1.25×').click()
  assert.equal((await audio()).speed, 1.25)
  await button('整词入场').click()
  assert.equal(await button('整词入场').getAttribute('aria-pressed'), 'true')
  await page.keyboard.press('Escape')
  await page.locator('.captions-control').click()
  assert.equal(await page.locator('.captions-control').getAttribute('aria-pressed'), 'false')
  await page.locator('.captions-control').click()
  await button('音量设置').click()
  await page.getByRole('slider', { name: '音量', exact: true }).focus()
  await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight')
  assert.ok((await audio()).volume < .03)
  await button('静音').click()
  assert.equal((await audio()).muted, true)
  await page.keyboard.press('Escape')
  pass('Playback rate, word mode, caption toggle, volume and mute')
  await button('同步歌词').click()
  assert.equal(await page.locator('.lyric-row').count(), 41)
  await page.locator('[data-line="20"]').click()
  await page.waitForTimeout(200)
  assert.equal(await page.evaluate(() => window.lastUserSeek), 71.512)
  assert.ok((await audio()).time >= 71.5)
  await button('暂停').click()
  pass('All 41 lyric lines and per-line seeking')
  await button('角色档案').click()
  assert.equal(await page.locator('.cast-entry').count(), 8)
  await page.locator('.cast-entry').nth(4).click()
  assert.equal(await page.getByRole('dialog').count(), 1)
  await page.getByRole('button', { name: /观看出场镜头/ }).click()
  assert.equal(await page.evaluate(() => window.lastUserSeek), 53.973)
  assert.ok((await audio()).time >= 53.97)
  pass('Eight original character records and first-appearance jump')
  await button('全屏放映').click()
  await page.waitForTimeout(180)
  assert.ok(await page.evaluate(() => !!document.fullscreenElement || !!document.querySelector('.fallback-full')))
  await button('退出全屏').click()
  pass('Fullscreen entrance and exit')
  await page.locator('audio').evaluate(a => { a.currentTime = a.duration-.15 })
  await page.locator('.end-screen').waitFor()
  await page.locator('.end-screen').getByRole('button', { name: '重新放映' }).click()
  assert.equal(await page.evaluate(() => window.lastUserSeek), 0)
  await button('鲸映，返回放映厅').click()
  pass('Film ending, replay and cover reset')
  await button('收藏作品').click(); await page.reload({ waitUntil: 'networkidle' })
  assert.equal(await button('已收藏').getAttribute('aria-pressed'), 'true')
  await button('已收藏').click()
  pass('Saved film persists after reload')
  await button('创作手记').click(); await button('素材与制作').click()
  assert.equal(await page.getByRole('link', { name: /下载成片/ }).count(), 1)
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  await button('快捷键').click(); await button('关闭窗口').click()
  pass('Director notes, production credits, downloads and accessible dialogs')
  assert.deepEqual(errors, [])
  pass('No uncaught browser errors')
  await writeFile(`${out}/summary.json`, JSON.stringify({ checks, errors }, null, 2))
} finally { await browser.close() }