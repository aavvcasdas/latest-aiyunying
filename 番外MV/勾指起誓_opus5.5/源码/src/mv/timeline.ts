export function shotAt(b: number): number {
  let lo = 0, hi = SHOTS.length - 1;
  while (lo < hi) { const m = (lo + hi + 1) >> 1; if (SHOTS[m].b0 <= b) lo = m; else hi = m - 1; }
  return lo;
}
export function lineAt(b: number): number {
  for (let i = LINES.length - 1; i >= 0; i--) if (b >= LINES[i].b0 - 0.2) return b < LINES[i].b1 ? i : -1;
  return -1;
}
